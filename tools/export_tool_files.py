"""Export case-sensitive tool entry files OUTSIDE the submission repository."""
import argparse
from pathlib import Path
import shutil

root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--dest',required=True,type=Path)
a=p.parse_args(); dest=a.dest.resolve()
if dest==root or root in dest.parents:
    p.error('--dest must be outside the submission tree')
if dest.exists() and any(dest.iterdir()):
    p.error('destination must be empty or absent')
shutil.copytree(root,dest,dirs_exist_ok=True,ignore=shutil.ignore_patterns('__pycache__'))
for f in list(dest.rglob('skill.md')):
    f.rename(f.with_name('SKILL.md'))
# Skill scripts must use the canonical entry name in the exported installable tree.
for f in dest.joinpath('skill').rglob('*'):
    if f.suffix in ('.py','.md','.json'):
        f.write_text(f.read_text(encoding='utf-8').replace('skill.md','SKILL.md'),encoding='utf-8')
c=dest/'src/ps/vitis_app_config'
(c/'cmakelists.txt').rename(c/'CMakeLists.txt')
u=c/'userconfig.cmake'
u.write_text(u.read_text().replace('${CMAKE_CURRENT_LIST_DIR}/../app_src',(dest/'src/ps/app_src').as_posix()),encoding='utf-8')
print('EXPORTED:',dest)
print('Use exported SKILL.md directories for skill import.')
print('Vitis: create platform from src/ps/hw/dpd_legacy_hw.xsa, then empty C app.')
print('Replace generated app src CMake/config files from exported vitis_app_config.')
print('Copy CMakeLists.txt, empty_applicationexample.cmake, userconfig.cmake, lscript.ld; keep the new app.yaml generated by Vitis.')
